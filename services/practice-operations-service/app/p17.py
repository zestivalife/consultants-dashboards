def resolve_permissions(role, grants=(), restrictions=(), capabilities=()):
    """Resolve governed defaults, bounded overrides, then profession capability gates."""
    base = set(ROLE_PERMISSIONS.get(role, ()))
    if role == "PRACTICE_OWNER":
        base |= set(grants) & PERMISSIONS
    else:
        base |= (set(grants) & PERMISSIONS & set(ROLE_PERMISSIONS["PRACTICE_OWNER"]))
    base -= set(restrictions)
    enabled = set(capabilities)
    return frozenset(p for p in base if not CAPABILITY_PERMISSIONS.get(p) or CAPABILITY_PERMISSIONS[p] in enabled)


def can_manage_role(actor_role, target_role, new_role):
    if new_role == "PRACTICE_OWNER":
        return False
    if actor_role == "PRACTICE_OWNER":
        return target_role != "PRACTICE_OWNER"
    return actor_role == "PRACTICE_ADMIN" and target_role not in {"PRACTICE_OWNER", "PRACTICE_ADMIN"}
