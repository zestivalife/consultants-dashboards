#!/bin/sh
set -eu

repository_root=$(git rev-parse --show-toplevel)
revision=$(git -C "$repository_root" rev-parse --verify HEAD)
case "$revision" in
  [0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]) ;;
  *) echo "Refusing to package an invalid Git revision" >&2; exit 1 ;;
esac

destination="$repository_root/services/auth-service/.source-revision"
printf '%s\n' "$revision" > "$destination"
printf 'Packaged Auth source revision %s\n' "$revision"
